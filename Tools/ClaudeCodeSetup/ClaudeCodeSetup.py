class InstallerLogic:
    """Headless installation logic for the Claude Code observer layer.

    Receives log and status callbacks from the GUI so all output can be
    displayed without this class depending on tkinter directly.
    """

    def __init__(self, log_cb, status_cb):
        """Initialise with GUI callback functions.

        Args:
            log_cb:    fn(message, tag) — appends a line to the log widget.
            status_cb: fn(message, level) — updates the status bar.
        """
        self.log    = log_cb
        self.status = status_cb

    def run_step(self, label: str, fn) -> bool:
        """Execute a single installation step and log the result.

        Args:
            label: Human-readable step name shown in the log.
            fn:    Zero-argument callable that raises on failure.

        Returns:
            True if fn completed without exception, False otherwise.
        """
        self.log(f"\n▶  {label}", "step")
        try:
            fn()
            self.log(f"   ✅ {label} — OK", "ok")
            return True
        except Exception as e:
            self.log(f"   ❌ {label} — FEHLER: {e}", "error")
            return False

    def check_python(self):
        """Raise RuntimeError if the running Python version is below 3.10."""
        v = sys.version_info
        if v.major < 3 or (v.major == 3 and v.minor < 10):
            raise RuntimeError(f"Python 3.10+ benötigt, gefunden: {v.major}.{v.minor}")
        self.log(f"      Python {v.major}.{v.minor}.{v.micro}", "info")

    # ── PATH HELPERS ─────────────────────────────────────────────────────────

    @staticmethod
    def _find_node_dir() -> str:
        """Return the directory containing node.exe, or '' if not found."""
        # 1. Already on PATH?
        node = shutil.which("node")
        if node:
            return os.path.dirname(node)
        # 2. Common Windows install locations
        candidates = [
            os.path.join(os.environ.get("ProgramFiles", "C:\\Program Files"), "nodejs"),
            os.path.join(os.environ.get("ProgramFiles(x86)", "C:\\Program Files (x86)"), "nodejs"),
            os.path.join(os.environ.get("APPDATA", ""), "nvm", "current"),
            os.path.join(os.environ.get("LOCALAPPDATA", ""), "Programs", "nodejs"),
        ]
        for c in candidates:
            if os.path.isfile(os.path.join(c, "node.exe")):
                return c
        return ""

    def _npm_cmd(self) -> list[str]:
        """Return a working npm invocation, trying npm.cmd / npm / full path."""
        # On Windows, npm ships as npm.cmd next to node.exe
        for candidate in ["npm.cmd", "npm"]:
            if shutil.which(candidate):
                return [candidate]
        node_dir = self._find_node_dir()
        if node_dir:
            npm_cmd = os.path.join(node_dir, "npm.cmd")
            if os.path.isfile(npm_cmd):
                return [npm_cmd]
            npm_js = os.path.join(node_dir, "node_modules", "npm", "bin", "npm-cli.js")
            if os.path.isfile(npm_js):
                return ["node", npm_js]
        return ["npm"]  # last-resort, will fail with clear error

    def _claude_cmd(self) -> list[str]:
        """Return a working claude invocation."""
        for candidate in ["claude.cmd", "claude"]:
            if shutil.which(candidate):
                return [candidate]
        node_dir = self._find_node_dir()
        if node_dir:
            # npm global bin is usually same dir as node on Windows
            for name in ["claude.cmd", "claude"]:
                p = os.path.join(node_dir, name)
                if os.path.isfile(p):
                    return [p]
            # Also check %APPDATA%\npm
            npm_bin = os.path.join(os.environ.get("APPDATA", ""), "npm")
            for name in ["claude.cmd", "claude"]:
                p = os.path.join(npm_bin, name)
                if os.path.isfile(p):
                    return [p]
        return ["claude"]

    # ── CHECKS ───────────────────────────────────────────────────────────────

    def check_node(self):
        """Raise RuntimeError if Node.js is not installed or not on PATH."""
        node_dir = self._find_node_dir()
        if node_dir:
            r = subprocess.run(
                [os.path.join(node_dir, "node.exe"), "--version"],
                capture_output=True, text=True
            )
        else:
            r = subprocess.run(["node", "--version"], capture_output=True, text=True)
        if r.returncode != 0 or not r.stdout.strip():
            raise RuntimeError(
                "Node.js nicht gefunden.\n"
                "      Installieren: winget install OpenJS.NodeJS.LTS\n"
                "      Danach PowerShell neu starten und Setup erneut ausführen."
            )
        self.log(f"      Node.js {r.stdout.strip()}", "info")
        if node_dir:
            self.log(f"      Pfad: {node_dir}", "info")

    def check_npm(self):
        """Raise RuntimeError if npm is not reachable via the resolved command."""
        npm = self._npm_cmd()
        r   = subprocess.run(npm + ["--version"], capture_output=True, text=True, shell=False)
        if r.returncode != 0 or not r.stdout.strip():
            # Give a precise fix hint
            node_dir = self._find_node_dir()
            hint = (
                f"\n      Node-Verzeichnis gefunden: {node_dir}" if node_dir else
                "\n      Node.js Verzeichnis nicht gefunden."
            )
            raise RuntimeError(
                f"npm nicht im PATH.{hint}\n"
                "      Fix: Füge den Node.js-Ordner zum System-PATH hinzu:\n"
                "      SystemProperties → Umgebungsvariablen → Path → Neu → <Node-Pfad>\n"
                "      Oder: Installer übernimmt das automatisch (Schaltfläche unten)."
            )
        self.log(f"      npm {r.stdout.strip()} ({' '.join(npm)})", "info")

    def check_claude_code(self):
        """Raise RuntimeError if the claude CLI is not installed or not executable."""
        claude = self._claude_cmd()
        r      = subprocess.run(claude + ["--version"], capture_output=True, text=True, shell=False)
        if r.returncode != 0 or not r.stdout.strip():
            raise RuntimeError(
                "Claude Code nicht installiert.\n"
                "      → Klicke 'npm fix + Claude Code installieren' unten."
            )
        self.log(f"      Claude Code: {r.stdout.strip()} ({' '.join(claude)})", "info")

    def fix_npm_path_and_install_claude(self, log_cb):
        """Add Node dir to user PATH and install Claude Code via npm."""
        node_dir = self._find_node_dir()
        if not node_dir:
            raise RuntimeError(
                "Node.js-Verzeichnis nicht gefunden.\n"
                "Bitte Node.js installieren: winget install OpenJS.NodeJS.LTS"
            )

        # 1. Add node_dir to current process PATH so npm works immediately
        current_path = os.environ.get("PATH", "")
        if node_dir.lower() not in current_path.lower():
            os.environ["PATH"] = node_dir + os.pathsep + current_path
            log_cb(f"      PATH ergänzt: {node_dir}", "ok")

        # 2. Also persist to user PATH via PowerShell (survives reboot)
        ps_cmd = (
            f'$p = [Environment]::GetEnvironmentVariable("Path","User");'
            f'if ($p -notlike "*{node_dir}*") {{'
            f'  [Environment]::SetEnvironmentVariable("Path", $p + ";{node_dir}", "User");'
            f'  Write-Host "PATH aktualisiert"'
            f'}} else {{ Write-Host "PATH bereits vorhanden" }}'
        )
        r = subprocess.run(
            ["powershell", "-Command", ps_cmd],
            capture_output=True, text=True
        )
        log_cb(f"      {r.stdout.strip() or 'PATH-Schritt abgeschlossen'}", "info")

        # 3. npm install -g @anthropic-ai/claude-code
        npm = self._npm_cmd()
        log_cb(f"      Führe aus: {' '.join(npm)} install -g @anthropic-ai/claude-code", "info")
        log_cb("      (Dies kann 1-3 Minuten dauern…)", "info")

        proc = subprocess.Popen(
            npm + ["install", "-g", "@anthropic-ai/claude-code"],
            stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
            text=True, bufsize=1
        )
        for line in proc.stdout:
            line = line.rstrip()
            if line:
                log_cb(f"      {line}", "info")
        proc.wait()

        if proc.returncode != 0:
            raise RuntimeError(
                f"npm install fehlgeschlagen (exit {proc.returncode}).\n"
                "      Prüfe Internetverbindung und versuche es erneut."
            )
        log_cb("      Claude Code installiert ✅", "ok")

    def create_dirs(self, project_dir: str):
        """Create the ClaudeCode/, logs/ and scripts/ subdirectories inside project_dir."""
        dirs = [
            os.path.join(project_dir, "ClaudeCode"),
            os.path.join(project_dir, "ClaudeCode", "logs"),
            os.path.join(project_dir, "ClaudeCode", "scripts"),
        ]
        for d in dirs:
            os.makedirs(d, exist_ok=True)
            self.log(f"      📁 {d}", "info")

    def write_claude_md(self, project_dir: str, openclaw_dir: str):
        """Generate and write CLAUDE.md into project_dir."""
        path    = os.path.join(project_dir, "CLAUDE.md")
        content = build_claude_md(project_dir, openclaw_dir)
        with open(path, "w", encoding="utf-8") as f:
            f.write(content)
        self.log(f"      📄 {path}", "info")

    def write_scripts(self, project_dir: str, openclaw_dir: str):
        """Write the three PowerShell scripts (start / stop / uninstall) to project_dir.

        Files are encoded as UTF-8 with BOM (utf-8-sig) so PowerShell 5 reads
        non-ASCII characters correctly on systems with a non-UTF-8 default codepage.
        """
        scripts = {
            "lyra_observer.ps1":           build_observer_ps1(project_dir, openclaw_dir),
            "lyra_observer_stop.ps1":      build_stop_ps1(project_dir),
            "lyra_observer_uninstall.ps1": build_uninstall_ps1(project_dir),
        }
        for name, content in scripts.items():
            path = os.path.join(project_dir, name)
            # utf-8-sig writes UTF-8 BOM — required for PowerShell 5 to read
            # non-ASCII characters correctly (PS5 defaults to system codepage)
            with open(path, "w", encoding="utf-8-sig") as f:
                f.write(content)
            self.log(f"      📜 {path}", "info")

    def write_install_log(self, project_dir: str, openclaw_dir: str):
        """Write a timestamped installation log entry to ClaudeCode/logs/."""
        logs_dir = os.path.join(project_dir, "ClaudeCode", "logs")
        ts       = datetime.datetime.now()
        log_path = os.path.join(logs_dir, ts.strftime("%Y-%m-%d_%H-%M") + "_install.log")
        content  = (
            f"[{APP_VERSION}] {ts.strftime('%Y-%m-%d %H:%M:%S')}\n"
            f"ACTION   : Initial installation of Claude Code observer layer\n"
            f"WHY      : ClaudeCodeSetup.py run by user\n"
            f"WHERE    : {project_dir}\\ClaudeCode\n"
            f"BEFORE   : No observer layer present\n"
            f"AFTER    : CLAUDE.md + scripts + log folder created\n"
            f"OPENCLAW : {openclaw_dir}\n"
            f"RESULT   : SUCCESS\n"
        )
        with open(log_path, "w", encoding="utf-8") as f:
            f.write(content)
        self.log(f"      📋 {log_path}", "info")

    def install(self, project_dir: str, openclaw_dir: str):
        """Run the full installation sequence (all steps) for the given paths.

        Executes each step via run_step(). Continues on individual failures and
        reports overall success or partial failure via the status callback.
        """
        ok = True
        ok &= self.run_step("Python-Version prüfen",    self.check_python)
        ok &= self.run_step("Node.js prüfen",            self.check_node)
        ok &= self.run_step("npm prüfen",                self.check_npm)
        ok &= self.run_step("Claude Code prüfen",        self.check_claude_code)
        ok &= self.run_step("Ordner erstellen",          lambda: self.create_dirs(project_dir))
        ok &= self.run_step("CLAUDE.md schreiben",       lambda: self.write_claude_md(project_dir, openclaw_dir))
        ok &= self.run_step("Scripts schreiben",         lambda: self.write_scripts(project_dir, openclaw_dir))
        ok &= self.run_step("Install-Log schreiben",     lambda: self.write_install_log(project_dir, openclaw_dir))

        if ok:
            self.status("✅  Installation abgeschlossen", "ok")
            self.log("\n══════════════════════════════════════════", "step")
            self.log("  Alles bereit! Nächste Schritte:", "ok")
            self.log(f"  1. Terminal öffnen in: {project_dir}", "info")
            self.log("  2. PowerShell: .\\lyra_observer.ps1", "info")
            self.log("  3. Claude Code öffnet sich mit Lyra-Kontext", "info")
            self.log("  4. Sag: 'Lies SOUL.md und schlage Verbesserungen vor'", "info")
            self.log("══════════════════════════════════════════\n", "step")
        else:
            self.status("⚠️  Installation mit Fehlern — siehe Log", "warn")
            self.log("\n══════════════════════════════════════════", "warn")
            self.log("  Fehlgeschlagen? Falls npm/Claude Code fehlen:", "warn")
            self.log("  → Klicke  'npm fix + Claude Code installieren'", "warn")
            self.log("  → Danach nochmals INSTALLIEREN klicken", "warn")
            self.log("══════════════════════════════════════════\n", "warn")

    def start_observer(self, project_dir: str):
        """Launch lyra_observer.ps1 in a new visible terminal window.

        Prefers Windows Terminal (wt.exe) if available, falls back to cmd /c start.
        Claude Code requires an interactive terminal and cannot run headless.
        """
        script = os.path.join(project_dir, "lyra_observer.ps1")
        if not os.path.exists(script):
            raise RuntimeError("lyra_observer.ps1 nicht gefunden - bitte erst installieren.")

        # Claude Code ist interaktiver REPL - braucht echtes Terminal-Fenster.
        # Strategie 1: wt.exe (Windows Terminal)  2: cmd /c start
        ps_call = f'powershell.exe -ExecutionPolicy Bypass -NoExit -File "{script}"'

        wt = shutil.which("wt") or shutil.which("wt.exe")
        if wt:
            subprocess.Popen(
                f'"{wt}" --title "Claude Code Lyra" {ps_call}',
                shell=True, cwd=project_dir
            )
            self.log("  \U0001f680 Observer gestartet in Windows Terminal (wt.exe)", "ok")
            return

        # cmd /c start erzwingt neues sichtbares Konsolenfenster
        subprocess.Popen(
            f'cmd /c start "Claude Code Lyra" {ps_call}',
            shell=True, cwd=project_dir
        )
        self.log("  \U0001f680 Observer gestartet via cmd /c start", "ok")
        self.log(f"  \U0001f4c1 Arbeitsverzeichnis: {project_dir}", "info")
        self.log("", "info")
        self.log("  Falls kein Fenster erscheint - manuell starten:", "warn")
        self.log("  1. PowerShell oeffnen (Win+X Terminal)", "info")
        self.log(f'  2. cd "{project_dir}"', "info")
        self.log("  3. .\\lyra_observer.ps1", "info")

    def stop_observer(self, project_dir: str):
        """Execute lyra_observer_stop.ps1 to terminate all observer sessions."""
        script = os.path.join(project_dir, "lyra_observer_stop.ps1")
        if not os.path.exists(script):
            raise RuntimeError("lyra_observer_stop.ps1 nicht gefunden — bitte erst installieren.")
        r = subprocess.run(
            ["powershell", "-ExecutionPolicy", "Bypass", "-File", script],
            capture_output=True, text=True
        )
        self.log(r.stdout or "Gestoppt.", "info")

    def uninstall(self, project_dir: str):
        """Launch lyra_observer_uninstall.ps1 in a new console window."""
        script = os.path.join(project_dir, "lyra_observer_uninstall.ps1")
        if not os.path.exists(script):
            raise RuntimeError("lyra_observer_uninstall.ps1 nicht gefunden.")
        subprocess.Popen(
            ["powershell", "-ExecutionPolicy", "Bypass", "-File", script],
            creationflags=subprocess.CREATE_NEW_CONSOLE
        )
        self.log("  🗑️  Uninstaller gestartet (neues Terminal-Fenster)", "ok")


